// Evolution mapping: get available upgrades for current class at current level
export function getAvailableUpgrades(currentClassId: TankClassId, level: number): TankDefinition[] {
  const current = TANK_CLASSES[currentClassId];
  if (!current) return [];

  const results: TankDefinition[] = [];
  const targetTier = current.tier === 1 && level >= 15 ? 2 : current.tier === 2 && level >= 30 ? 3 : current.tier === 3 && level >= 45 ? 4 : null;

  if (!targetTier) return [];

  for (const key of Object.keys(TANK_CLASSES) as TankClassId[]) {
    const candidate = TANK_CLASSES[key];
    if (candidate.tier === targetTier && candidate.parentClass?.includes(currentClassId)) {
      results.push(candidate);
    }
  }

  return results;
}

// XP table generator (Diep.io style polynomial XP requirements for levels 1-45)
export const XP_REQUIREMENTS: number[] = [0];
let totalXp = 0;
for (let lvl = 1; lvl <= 45; lvl++) {
  if (lvl === 1) {
    XP_REQUIREMENTS.push(20);
    totalXp = 20;
  } else {
    // exponential growth formula
    const needed = Math.floor(20 * Math.pow(lvl, 1.65));
    totalXp += needed;
    XP_REQUIREMENTS.push(totalXp);
  }
}

// Total cumulative XP needed to reach targetLevel from level 1
export function getTotalXpForLevel(targetLevel: number): number {
  let sum = 0;
  for (let i = 1; i < targetLevel && i < XP_REQUIREMENTS.length; i++) {
    sum += XP_REQUIREMENTS[i];
  }
  return sum;
}
